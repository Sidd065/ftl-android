#!/usr/bin/env python3
"""Generate symbols_cxx.c: maps the game's C++ runtime imports (Mach-O names)
to the hidden symbols of our Apple-ABI libc++/libc++abi/libunwind build."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from macho import MachO
m = MachO(sys.argv[1])
syms = set()
for kind in ('bind', 'lazy', 'weak'):
    for addr, sym, ordn, add, typ, fl in m.binds(kind):
        if sym.startswith('__Z') or sym.startswith('___cxa_') or sym in ('___gxx_personality_v0', '__Unwind_Resume'):
            if sym == '___cxa_atexit':
                continue
            syms.add(sym)
out = ['// Generated by tools/gen_cxx_syms.py -- do not edit.', '#include "symbols.h"', '']
for s in sorted(syms):
    out.append(f'extern char {s[1:]}[];')
out.append('')
out.append('const sym_entry g_cxx_syms[] = {')
for s in sorted(syms):
    out.append(f'    {{"{s}", (void *){s[1:]}}},')
out.append('    {0, 0}')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(syms), "C++ symbols")
